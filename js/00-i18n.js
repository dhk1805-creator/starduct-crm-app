const _rxEsc=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const _F_EN=FRAG.slice().sort((a,b)=>b[0].length-a[0].length);            // VI→EN: sắp theo VI dài trước
const _F_VI=FRAG.slice().sort((a,b)=>b[1].length-a[1].length)             // EN→VI: sắp theo EN dài trước
  .map(([v,e])=>[v,e,/^[A-Za-z0-9].*[A-Za-z0-9]$/.test(e)?new RegExp('\\b'+_rxEsc(e)+'\\b','g'):null]);
function _translate(s,en){
  if(en){for(const [v,e] of _F_EN){if(s.includes(v))s=s.split(v).join(e)}}
  else{for(const [v,e,rx] of _F_VI){
    if(!s.includes(e))continue;
    s=rx?s.replace(rx,v):s.split(e).join(v);               // mảnh có emoji/ký tự đặc biệt: thay trực tiếp
  }}
  return s;
}
const t=s=>LANG==='en'?_translate(s,true):s;               // dùng cho prompt/alert/msg động
function applyLang(){
  const en=LANG==='en';
  (function walk(n){
    if(n.nodeType===3){if(n.nodeValue.trim())n.nodeValue=_translate(n.nodeValue,en)}
    else if(n.nodeType===1){
      if(n.placeholder)n.placeholder=_translate(n.placeholder,en);
      if(n.title)n.title=_translate(n.title,en);
      for(const c of n.childNodes)walk(c)}
  })(document.body);
  // các option tĩnh có emoji không tự đảo chiều được — đặt lại tường minh
  modSel.options[0].text=en?'🇻🇳 DOMESTIC MARKET':'🇻🇳 THỊ TRƯỜNG NỘI ĐỊA';
  modSel.options[1].text=en?'🌏 INTERNATIONAL MARKET':'🌏 THỊ TRƯỜNG QUỐC TẾ';
  if(frvXem.options[0])frvXem.options[0].text=en?'👑 Full view (Manager/CEO)':'👑 Toàn cảnh (Manager/CEO)';
  langBtn.textContent=en?'VI':'EN';
  document.documentElement.lang=en?'en':'vi';
}
